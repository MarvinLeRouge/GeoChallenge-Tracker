"""Application errors carrying a stable, machine-readable code.

The code is returned in the error envelope (`error.code`) so clients can show a
localized message; `detail` stays an English message for logs and API users.
"""

from enum import StrEnum
from typing import Any

from fastapi import HTTPException


class ErrorCode(StrEnum):
    """Every error code the API can return in `error.code` (besides generic `HTTP_<status>`)."""

    # Auth and accounts
    ADMIN_ONLY = "ADMIN_ONLY"
    NOT_AUTHENTICATED = "NOT_AUTHENTICATED"
    INVALID_CREDENTIALS = "INVALID_CREDENTIALS"
    MISSING_CREDENTIALS = "MISSING_CREDENTIALS"
    UNVERIFIED_USER = "UNVERIFIED_USER"
    INVALID_TOKEN = "INVALID_TOKEN"
    NO_REFRESH_TOKEN = "NO_REFRESH_TOKEN"
    INVALID_REFRESH_TOKEN = "INVALID_REFRESH_TOKEN"
    VERIFICATION_CODE_INVALID = "VERIFICATION_CODE_INVALID"
    USERNAME_OR_EMAIL_TAKEN = "USERNAME_OR_EMAIL_TAKEN"
    USER_CREATION_FAILED = "USER_CREATION_FAILED"
    USER_NOT_FOUND = "USER_NOT_FOUND"
    USER_ID_MISSING = "USER_ID_MISSING"
    INVALID_USER_ID = "INVALID_USER_ID"
    PASSWORD_TOO_SHORT = "PASSWORD_TOO_SHORT"
    PASSWORD_NO_UPPERCASE = "PASSWORD_NO_UPPERCASE"
    PASSWORD_NO_LOWERCASE = "PASSWORD_NO_LOWERCASE"
    PASSWORD_NO_DIGIT = "PASSWORD_NO_DIGIT"
    PASSWORD_NO_SPECIAL = "PASSWORD_NO_SPECIAL"
    FORCE_ADMIN_ONLY = "FORCE_ADMIN_ONLY"

    # Rate limiting and generic validation
    RATE_LIMIT_EXCEEDED = "RATE_LIMIT_EXCEEDED"
    VALIDATION_ERROR = "VALIDATION_ERROR"
    INTERNAL_ERROR = "INTERNAL_ERROR"

    # Uploads and GPX import
    FILE_TOO_LARGE = "FILE_TOO_LARGE"
    FILE_DECODE_FAILED = "FILE_DECODE_FAILED"
    GPX_TOO_SMALL = "GPX_TOO_SMALL"
    GPX_MISSING_ROOT = "GPX_MISSING_ROOT"
    GPX_FILE_NOT_FOUND = "GPX_FILE_NOT_FOUND"
    GPX_FILE_EMPTY = "GPX_FILE_EMPTY"
    GPX_READ_FAILED = "GPX_READ_FAILED"
    GPX_IMPORT_INVALID = "GPX_IMPORT_INVALID"
    ZIP_INVALID = "ZIP_INVALID"
    ZIP_NO_GPX = "ZIP_NO_GPX"
    ZIP_TOO_MANY_FILES = "ZIP_TOO_MANY_FILES"
    ZIP_TOO_LARGE = "ZIP_TOO_LARGE"
    ZIP_EXTRACTION_FAILED = "ZIP_EXTRACTION_FAILED"

    # Caches, zones and geo
    CACHE_NOT_FOUND = "CACHE_NOT_FOUND"
    INVALID_OBJECT_ID = "INVALID_OBJECT_ID"
    GEO_INDEX_MISSING = "GEO_INDEX_MISSING"
    INVALID_COUNTRY_CODE = "INVALID_COUNTRY_CODE"
    ZONE_UPLOAD_INVALID = "ZONE_UPLOAD_INVALID"
    ZONE_COUNTRY_REQUIRED = "ZONE_COUNTRY_REQUIRED"
    ZONE_NOT_FOUND = "ZONE_NOT_FOUND"

    # Profile and challenges
    LOCATION_INVALID = "LOCATION_INVALID"
    LOCATION_NOT_FOUND = "LOCATION_NOT_FOUND"
    STATS_NOT_FOUND = "STATS_NOT_FOUND"
    USER_CHALLENGE_NOT_FOUND = "USER_CHALLENGE_NOT_FOUND"
    USER_CHALLENGE_UPDATE_FAILED = "USER_CHALLENGE_UPDATE_FAILED"
    BATCH_TOO_LARGE = "BATCH_TOO_LARGE"
    TASKS_INVALID = "TASKS_INVALID"
    TARGETS_RADIUS_REQUIRED = "TARGETS_RADIUS_REQUIRED"

    # Maintenance
    BACKUP_INVALID_PATH = "BACKUP_INVALID_PATH"
    BACKUP_NOT_FOUND = "BACKUP_NOT_FOUND"
    BACKUP_ARCHIVE_INVALID = "BACKUP_ARCHIVE_INVALID"
    CONFIRMATION_KEY_INVALID = "CONFIRMATION_KEY_INVALID"
    CONFIRMATION_KEY_EXPIRED = "CONFIRMATION_KEY_EXPIRED"
    CONFIRMATION_KEY_MISMATCH = "CONFIRMATION_KEY_MISMATCH"


class AppError(HTTPException):
    """HTTPException with an `ErrorCode`, rendered as `error.code` by the global handler."""

    def __init__(
        self,
        status_code: int,
        code: ErrorCode,
        detail: Any = None,
        headers: dict[str, str] | None = None,
    ) -> None:
        super().__init__(status_code=status_code, detail=detail, headers=headers)
        self.code = code
